import type { Brief, Metrics, PublishRecord, Severity } from "../src/shared/types"
import { config } from "./config"

const HEALTH_EMOJI = { Green: ":large_green_circle:", Yellow: ":large_yellow_circle:", Red: ":red_circle:" }
const SEVERITY_LABEL: Record<Severity, string> = {
  high: ":rotating_light: *High*",
  medium: ":warning: *Medium*",
  low: ":small_blue_diamond: Low",
}

/** Slack mrkdwn needs &, < and > escaped in user content. */
export const escapeMrkdwn = (value: string) =>
  value.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")

const bullets = (items: string[]) => items.map((item) => `• ${escapeMrkdwn(item)}`).join("\n")

export const weekOf = (now = new Date()) => {
  const monday = new Date(now)
  monday.setUTCDate(monday.getUTCDate() - ((monday.getUTCDay() + 6) % 7))
  return monday.toLocaleDateString("en-US", { month: "short", day: "numeric", timeZone: "UTC" })
}

/** Plain mrkdwn version: notification text, webhook fallback and UI preview. */
export const briefToText = (brief: Brief, metrics: Metrics, now = new Date()) => {
  const lines = [
    `*BizOps Weekly Brief · Week of ${weekOf(now)}*`,
    `${HEALTH_EMOJI[metrics.health]} *${escapeMrkdwn(brief.headline)}*`,
    "",
    escapeMrkdwn(brief.summary),
    "",
    `*Delivery:* ${metrics.completedTasks}/${metrics.totalTasks} done · ${metrics.averageProgress}% avg progress · ${metrics.confidence}% confidence`,
  ]
  if (brief.wins.length) lines.push("", "*Wins*", bullets(brief.wins))
  if (brief.risks.length) {
    lines.push(
      "",
      "*Risks & actions*",
      ...brief.risks.map(
        (risk) =>
          `${SEVERITY_LABEL[risk.severity]} · *${escapeMrkdwn(risk.project)}* (${escapeMrkdwn(risk.owner)}): ${escapeMrkdwn(risk.issue)}\n    ↳ ${escapeMrkdwn(risk.action)}`,
      ),
    )
  }
  if (brief.leadershipAsks.length) lines.push("", "*Asks for leadership*", bullets(brief.leadershipAsks))
  if (brief.nextWeekFocus.length) lines.push("", "*Next week*", bullets(brief.nextWeekFocus))
  return lines.join("\n")
}

export const briefToBlocks = (brief: Brief, metrics: Metrics, now = new Date()) => {
  const section = (text: string) => ({ type: "section", text: { type: "mrkdwn", text } })
  const blocks: any[] = [
    { type: "header", text: { type: "plain_text", text: `BizOps Weekly Brief · Week of ${weekOf(now)}` } },
    section(`${HEALTH_EMOJI[metrics.health]} *${escapeMrkdwn(brief.headline)}*\n${escapeMrkdwn(brief.summary)}`),
    {
      type: "section",
      fields: [
        { type: "mrkdwn", text: `*Health*\n${metrics.health} · ${metrics.confidence}%` },
        { type: "mrkdwn", text: `*Delivered*\n${metrics.completedTasks}/${metrics.totalTasks} items` },
        { type: "mrkdwn", text: `*Blocked / at risk*\n${metrics.blockedTasks} / ${metrics.atRiskTasks}` },
        { type: "mrkdwn", text: `*Overdue*\n${metrics.overdueTasks}` },
      ],
    },
  ]

  if (brief.wins.length) blocks.push({ type: "divider" }, section(`*Wins*\n${bullets(brief.wins)}`))
  if (brief.risks.length) {
    blocks.push({ type: "divider" }, section("*Risks & actions*"))
    for (const risk of brief.risks) {
      blocks.push(
        section(
          `${SEVERITY_LABEL[risk.severity]} · *${escapeMrkdwn(risk.project)}* — ${escapeMrkdwn(risk.issue)}\n↳ ${escapeMrkdwn(risk.action)} _(${escapeMrkdwn(risk.owner)})_`,
        ),
      )
    }
  }
  if (brief.leadershipAsks.length)
    blocks.push({ type: "divider" }, section(`*Asks for leadership*\n${bullets(brief.leadershipAsks)}`))
  if (brief.nextWeekFocus.length) blocks.push(section(`*Next week*\n${bullets(brief.nextWeekFocus)}`))
  blocks.push({
    type: "context",
    elements: [{ type: "mrkdwn", text: "Generated by BizOps Standup Agent · passed automated quality gates" }],
  })
  // Slack caps messages at 50 blocks.
  return blocks.slice(0, 50)
}

export const slackMode = (): PublishRecord["mode"] =>
  config.slack.botToken ? "bot" : config.slack.webhookUrl ? "webhook" : "dry_run"

export const postToSlack = async (
  channel: string,
  text: string,
  blocks: any[],
): Promise<{ mode: PublishRecord["mode"]; permalink?: string }> => {
  const mode = slackMode()

  if (mode === "bot") {
    const response = await fetch("https://slack.com/api/chat.postMessage", {
      method: "POST",
      headers: {
        Authorization: `Bearer ${config.slack.botToken}`,
        "Content-Type": "application/json; charset=utf-8",
      },
      body: JSON.stringify({ channel, text, blocks, unfurl_links: false }),
    })
    const json: any = await response.json()
    if (!json.ok) throw new Error(`Slack chat.postMessage failed: ${json.error}`)

    const link = await fetch(
      `https://slack.com/api/chat.getPermalink?channel=${json.channel}&message_ts=${json.ts}`,
      { headers: { Authorization: `Bearer ${config.slack.botToken}` } },
    )
      .then((res) => res.json() as Promise<any>)
      .catch(() => null)
    return { mode, permalink: link?.ok ? link.permalink : undefined }
  }

  if (mode === "webhook") {
    const response = await fetch(config.slack.webhookUrl!, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ text, blocks }),
    })
    if (!response.ok) throw new Error(`Slack webhook ${response.status}: ${await response.text()}`)
    return { mode }
  }

  return { mode }
}
